// The characters of Ming Suzhou's writing (docs/settlements/ming-suzhou.md §22): traditional forms in regular
// script, each a list of strokes for brush.js on a 100-unit grid (y up). Kinds: h heng, s shu (dewdrop),
// x shu (needle), p pie, n na, d dian, t ti, sg shu-gou, hz heng-zhe, hzg heng-zhe-gou, sz shu-zhe, hg heng-gou,
// wg wo-gou, hp heng-pie, e even level stroke. Every entry is checked stroke by stroke against the standard form
// (tools/script-sheet.mjs) and its stroke count is the standard count (listed in the dossier).

/** Strokes of a component, placed in the box x0…x1 × y0…y1 (the component's own box is 0…100). */
const at = (comp, x0, y0, x1, y1) => comp.map(([k, ...v]) => {
  const o = [k];
  for (let i = 0; i + 1 < v.length; i += 2) o.push(x0 + v[i] * (x1 - x0) / 100, y0 + v[i + 1] * (y1 - y0) / 100);
  for (let i = v.length - (v.length % 2); i < v.length; i++) o.push(v[i]);
  return o;
});

