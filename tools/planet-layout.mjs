#!/usr/bin/env node
// Where every settlement stands on the planet (docs/world.md, "Layout").
//
// 1. Earth is mapped onto the planet through a few mild lenses that magnify the crowded parts of
//    the world (src/planet/warp.js); the land and the settlements' true places go through the same map.
// 2. The settlements then push each other apart until every two of them are at least
//    `spacing(a, b)` apart (src/planet/sites.js), held to their mapped places and kept on land
//    (most of their disc on the land). Settlements that share a place start a little off it (`nudge`).
//    What is left — how far each stands from its mapped true place — is reported; the lenses are
//    tuned to keep it small without bending the continents out of shape.
//
// Writes src/planet/layout.js. usage: node tools/planet-layout.mjs

import { writeFile } from 'node:fs/promises';
import { SITES, spacing, PLANET_RADIUS as R } from '../src/planet/sites.js';
import { unit, latLon, angle, travel, bearing } from '../src/planet/geo.js';
import { earthRings, mapRings, signedDistance, sampleGrid } from './lib/land.mjs';

// the lenses: centre [lat, lon], magnification at the centre, radius (degrees). Applied in order.
export const LENSES = [
  { name: 'Europe and the Near East', at: [40, 18], m: 1.5, r: 26 },
  { name: 'India', at: [22, 79], m: 1.3, r: 12 },
  { name: 'East Asia', at: [34, 120], m: 1.35, r: 14 },
];

const write = (placed) => writeFile(new URL('../src/planet/layout.js', import.meta.url), `// Generated by tools/planet-layout.mjs — do not edit by hand (docs/world.md, "Layout").
// LENSES: the map of Earth onto the planet (src/planet/warp.js).
// PLACED: where each settlement's centre stands on the planet [lat, lon] (degrees).

export const LENSES = ${JSON.stringify(LENSES.map(({ at, m, r }) => ({ at, m, r })))};

export const PLACED = {
${Object.entries(placed).map(([k, v]) => `  '${k}': [${v[0]}, ${v[1]}],`).join('\n')}
};
`);
await write({});
const { mapEarth } = await import(`../src/planet/warp.js?${Date.now()}`);

// the land, coarsely, for keeping settlements on it
const GW = 1024, GH = GW / 2;
const sdf = signedDistance(mapRings(await earthRings('50m'), mapEarth, 0.3), GW, R, 2);
const coast = (u) => { const [la, lo] = latLon(u); return sampleGrid(sdf, GW, GH, la, lo); };

const t = SITES.map((s) => mapEarth(unit(s.lat, s.lon)));
let x = t.map((u, i) => (SITES[i].nudge !== undefined ? travel(u, SITES[i].nudge * Math.PI / 180, 300 / R) : u.slice()));
const step = 2 / R;
for (let it = 0; it < 7000; it++) {
  const k = it < 4000 ? 0.5 : 0.25, landPull = true;
  for (let i = 0; i < x.length; i++) for (let j = i + 1; j < x.length; j++) {
    const need = spacing(SITES[i], SITES[j]) / R * 1.01, a = angle(x[i], x[j]);
    if (a >= need) continue;
    const push = (need - a) / 2 * k;
    const bi = bearing(x[i], x[j]), bj = bearing(x[j], x[i]);
    x[i] = travel(x[i], bi + Math.PI, push);
    x[j] = travel(x[j], bj + Math.PI, push);
  }
  for (let i = 0; i < x.length; i++) {
    const a = angle(x[i], t[i]);
    if (a > 1e-9) x[i] = travel(x[i], bearing(x[i], t[i]), a * 0.004);
    // onto the land: climb the distance to the coast while the disc is mostly over water
    const want = SITES[i].radius * 1.0, d = coast(x[i]);
    if (landPull && !SITES[i].water && d < want) {
      const gx = coast(travel(x[i], Math.PI / 2, step)) - coast(travel(x[i], -Math.PI / 2, step));
      const gy = coast(travel(x[i], 0, step)) - coast(travel(x[i], Math.PI, step));
      if (Math.hypot(gx, gy) > 1e-9) x[i] = travel(x[i], Math.atan2(gx, gy), Math.min(want - d, 40) / R * 0.5);
    }
  }
}
// last, spacing alone: settle any pair still too close (the pulls above can hold a crowded corner short)
// (still keeping centres on the land)
for (let it = 0; it < 1500; it++) {
  for (let i = 0; i < x.length; i++) for (let j = i + 1; j < x.length; j++) {
    const need = spacing(SITES[i], SITES[j]) / R * 1.01, a = angle(x[i], x[j]);
    if (a >= need) continue;
    const push = (need - a) / 2 * 0.5;
    const bi = bearing(x[i], x[j]), bj = bearing(x[j], x[i]);
    x[i] = travel(x[i], bi + Math.PI, push);
    x[j] = travel(x[j], bj + Math.PI, push);
  }
  for (let i = 0; i < x.length; i++) {
    if (SITES[i].water) continue;
    const d = coast(x[i]);
    if (d > 30) continue;
    const gx = coast(travel(x[i], Math.PI / 2, step)) - coast(travel(x[i], -Math.PI / 2, step));
    const gy = coast(travel(x[i], 0, step)) - coast(travel(x[i], Math.PI, step));
    if (Math.hypot(gx, gy) > 1e-9) x[i] = travel(x[i], Math.atan2(gx, gy), Math.min(30 - d, 20) / R * 0.5);
  }
}
let worst = Infinity, pair = null;
for (let i = 0; i < x.length; i++) for (let j = i + 1; j < x.length; j++) {
  const slack = angle(x[i], x[j]) * R - spacing(SITES[i], SITES[j]);
  if (slack < worst) { worst = slack; pair = [SITES[i].id, SITES[j].id]; }
}
const placed = {};
SITES.forEach((s, i) => { const [la, lo] = latLon(x[i]); placed[s.id] = [+la.toFixed(5), +lo.toFixed(5)]; });
await write(placed);
const off = SITES.map((s, i) => [s.id, Math.round(angle(t[i], x[i]) * R)]).sort((a, b) => b[1] - a[1]);
const wet = SITES.map((s, i) => [s.id, Math.round(s.radius - coast(x[i]))]).filter(([, d]) => d > 0).sort((a, b) => b[1] - a[1]);
console.log(`spacing: tightest pair ${pair.join(' – ')} has ${Math.round(worst)} m to spare`);
console.log('off their mapped true place (m):', off.slice(0, 20).map(([id, m]) => `${id} ${m}`).join(', '));
console.log('disc reaching over the water (m):', wet.map(([id, d]) => `${id} ${d}`).join(', ') || 'none');
