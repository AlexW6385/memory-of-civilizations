import { chromium } from 'playwright';
import { join } from 'node:path';
const ROOT = process.argv[2], q = process.argv[3] || '';
const { serve } = await import(join(ROOT, 'tools/serve.mjs'));
process.env.PLAYWRIGHT_BROWSERS_PATH ||= '/opt/pw-browsers';
const srv = await serve(0); const port = srv.address().port;
const browser = await chromium.launch({ args: ['--enable-unsafe-webgpu', '--enable-features=Vulkan', '--use-vulkan=swiftshader', '--use-webgpu-adapter=swiftshader', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 960, height: 600 } });
const t0 = Date.now();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message, e.stack?.slice(0, 800)));
page.on('requestfailed', (r) => console.log('REQFAIL', r.url()));
page.on('response', (r) => { if (r.status() >= 400) console.log('HTTP', r.status(), r.url()); });
page.on('console', (m) => { if (m.type() === 'error') console.log('CERR', m.text().slice(0, 800)); });
page.on('console', (m) => { const t = m.text(); if (t.includes('start (ms)')) console.log(((Date.now() - t0) / 1000).toFixed(1) + 's', t); });
await page.route('**/*', async (route) => { const url = route.request().url(); const m = url.match(/cdn\.jsdelivr\.net\/npm\/three@[^/]+\/(.*)$/); if (m) return route.fulfill({ path: join(ROOT, 'node_modules/three', m[1]), contentType: 'text/javascript' }); if (/fonts\.(googleapis|gstatic)/.test(url)) return route.abort(); return route.continue(); });
const iv = setInterval(async () => { try { console.log(((Date.now() - t0) / 1000).toFixed(0) + 's', await page.evaluate(() => document.getElementById('intro-status').textContent)); } catch {} }, 4000);
await page.goto(`http://127.0.0.1:${port}/index.html?time=10.5${q}`);
await page.waitForFunction('window.READY === true', null, { timeout: 1_200_000 });
clearInterval(iv); console.log('READY', ((Date.now() - t0) / 1000).toFixed(1) + 's');
await browser.close(); srv.close();
